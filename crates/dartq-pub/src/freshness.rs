    fn unobservable_env_keys_are_skipped() {
        let root = temp_dir("env-skip");
        write(&root.join("pubspec.yaml"), PUBSPEC);
        write(&root.join("pubspec.lock"), "packages: {}\n");
        write(
            &root.join(".dart_tool").join("package_config.json"),
            &CONFIG.replace(
                r#""generator": "pub""#,
                r#""generator": "pub", "flutterRoot": "file:///flutter""#,
            ),
        );
        set_file_mtime(
            root.join("pubspec.yaml"),
            FileTime::from_unix_time(1_000, 0),
        )
        .expect("set mtime");
        set_file_mtime(
            root.join("pubspec.lock"),
            FileTime::from_unix_time(2_000, 0),
        )
        .expect("set mtime");
        set_file_mtime(
            root.join(".dart_tool").join("package_config.json"),
            FileTime::from_unix_time(3_000, 0),
        )
        .expect("set mtime");

        // No flutter observation at all: recorded `flutterRoot` is skipped.
        let env = EnvSnapshot {
            dart_version: Some("3.13.1".into()),
            ..EnvSnapshot::default()
        };
        let report = Freshness::check(&root, &env, None);
        assert!(report.is_fresh(), "unexpected: {:?}", report.stale_reasons);

        // An observed, differing value still stales.
        let moved = EnvSnapshot {
            dart_version: Some("3.13.1".into()),
            flutter_root: Some("file:///moved".into()),
            ..EnvSnapshot::default()
        };
        let report = Freshness::check(&root, &moved, None);
        assert_eq!(
            report.stale_reasons,
            vec![StaleReason::EnvironmentChanged { key: "flutterRoot" }]
        );
    }

