/// Whether `name` — an options-file rule name in its written spelling —
/// names a rule the pinned registry knows (case-insensitive, the official
/// check rides the uppercased key). Cold path: once per options-file key.
pub(crate) fn is_known(name: &str) -> bool {
    let lowered = name.to_lowercase();
    NAMES.binary_search(&lowered.as_str()).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The #956 regression name: an official, implemented-elsewhere lint
    /// must pass the options-file validity faces.
    #[test]
    fn registered_but_unimplemented_names_pass() {
        assert!(is_known("avoid_print"));
        assert!(
            is_known("AVOID_PRINT"),
            "case-insensitive, the official uppercase compare"
        );
        assert!(is_known("avoid_as"), "removed rules register too");
    }

    /// The binary search contract: the table stays sorted and lowercase,
    /// and a truly unknown name misses.
    #[test]
    fn table_stays_sorted_and_unknown_names_miss() {
        assert!(NAMES.windows(2).all(|w| w[0] < w[1]));
        assert!(NAMES.iter().all(|n| *n == n.to_lowercase()));
        assert!(!is_known("not_a_real_code"));
        assert!(!is_known("not_a_lint"));
    }
}
