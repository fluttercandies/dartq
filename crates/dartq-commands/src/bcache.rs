//! Build-cache command glue: `dartq.yaml`'s `build_cache` section → the
//! shim orchestrator, `dartq init` (config scaffolding + `flutter`
//! PATH-shim install), and the `bcache stats|gc` maintenance faces.
//!
//! The zero-config contract lives here: with no `dartq.yaml` in the
//! cwd's upward chain, or one without an active `build_cache` section,
//! [`run_flutter_shim`] execs flutter with no store access at all —
//! existing behavior stays byte-identical. A malformed config on the
//! shim path is fail-open (one stderr note, then the passthrough
//! spawn): the shim must never block a build.

use std::ffi::{OsStr, OsString};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use dartq_bcache::orchestrator::{CommandRunner, FlutterRunner, ShimConfig, discover_flutter, run_shim};
use dartq_bcache::{BcacheError, CasStore, GcReport, StoreStats, STORE_LAYOUT_VERSION};

use crate::config::{BuildCacheConfig, ConfigError, load as load_config};

/// The default store size budget, in GiB.
const DEFAULT_BUDGET_GB: u64 = 40;
/// The default grace window, in seconds.
const DEFAULT_GRACE_SECS: u64 = 3600;

/// The `dartq.yaml` `dartq init` writes (only when none exists): the
/// `build_cache` section with every default commented to one line — the
/// cache activates once the user sets a key.
const CONFIG_TEMPLATE: &str = "\
# dartq workspace config. Generated by `dartq init`.
#
# build_cache: the `flutter` PATH shim's build cache. The shim is a pure
# passthrough until at least one key below is set.
build_cache:
  # root: ~/.cache/dartq/cas  # CAS store root (~ expands; default honors $XDG_CACHE_HOME)
  # budget_gb: 40             # store size budget in GiB
  # grace_secs: 3600          # seconds a recently-hit entry is unevictable
  # flutter: /path/to/flutter # explicit flutter binary (~ expands; default: PATH)
";

/// Expands a leading `~` to the home directory — the one tilde form the
/// config documents; other tildes stay literal. A home that cannot be
/// determined leaves the path untouched (the consumer surfaces it).
#[must_use]
pub fn expand_home(path: &Path) -> PathBuf {
    let Some(text) = path.to_str() else {
        return path.to_path_buf();
    };
    if text == "~"
        && let Some(home) = std::env::home_dir()
    {
        return home;
    }
    if let Some(rest) = text.strip_prefix("~/")
        && let Some(home) = std::env::home_dir()
    {
        return home.join(rest);
    }
    path.to_path_buf()
}

/// The orchestrator config a `build_cache` section (or its defaults)
/// maps to. `root` gains the store layer's layout version; `root` and
/// `flutter` both expand a leading `~` (a literal tilde would hand the
/// spawn a path the kernel cannot resolve — exit 127); the budget
/// saturates rather than overflow.
#[must_use]
pub fn shim_config(section: &BuildCacheConfig) -> ShimConfig {
    let root = match &section.root {
        Some(root) => expand_home(root),
        None => default_cache_root(),
    };
    ShimConfig {
        store_root: root.join(STORE_LAYOUT_VERSION),
        budget_bytes: section
            .budget_gb
            .unwrap_or(DEFAULT_BUDGET_GB)
            .saturating_mul(1024 * 1024 * 1024),
        grace_secs: section.grace_secs.unwrap_or(DEFAULT_GRACE_SECS),
        flutter_bin: section.flutter.as_ref().map(|bin| expand_home(bin)),
    }
}

/// The default store root, resolving exactly like the session
/// registry's cache root: `$XDG_CACHE_HOME/dartq/cas` when set, else
/// `~/.cache/dartq/cas`.
fn default_cache_root() -> PathBuf {
    cache_root_from(std::env::var_os("XDG_CACHE_HOME"), std::env::home_dir())
}

/// The resolution core of [`default_cache_root`], over injected
/// environment values (the test seam): XDG wins; a home joins
/// `.cache`; neither resolves to the process root.
fn cache_root_from(xdg_cache_home: Option<OsString>, home: Option<PathBuf>) -> PathBuf {
    xdg_cache_home
        .map(PathBuf::from)
        .or_else(|| home.map(|home| home.join(".cache")))
        .unwrap_or_default()
        .join("dartq")
        .join("cas")
}

/// The orchestrator config with every default applied (the maintenance
/// faces' store when no section is configured).
#[must_use]
pub fn default_shim_config() -> ShimConfig {
    shim_config(&BuildCacheConfig::default())
}

/// Finds the `dartq.yaml` governing `dir` — walking upward to the
/// filesystem root — and maps its `build_cache` section to a
/// [`ShimConfig`]. `Ok(None)`: no config, or one without an active
/// section (the zero-config passthrough).
///
/// # Errors
///
/// [`ConfigError::Invalid`] for a malformed config and
/// [`ConfigError::Io`] for an unreadable one, exactly as [`load_config`]
/// reports them.
pub fn discover_shim_config(dir: &Path) -> Result<Option<ShimConfig>, ConfigError> {
    let mut current = dir;
    loop {
        if let Some(config) = load_config(current)? {
            return Ok(config.build_cache.as_ref().map(shim_config));
        }
        match current.parent() {
            Some(parent) => current = parent,
            None => return Ok(None),
        }
    }
}

/// Whether this process was invoked as the `flutter` shim: argv0's
/// basename is `flutter` (the PATH symlink's name) or `flutter.exe`
/// (the Windows spelling), or `DARTQ_SHIM` is set (the explicit
/// spelling for wrappers that rename argv0).
#[must_use]
pub fn is_shim_invocation(argv0: Option<&OsStr>) -> bool {
    if std::env::var_os("DARTQ_SHIM").is_some_and(|value| !value.is_empty()) {
        return true;
    }
    argv0
        .and_then(|argv0| Path::new(argv0).file_name())
        .is_some_and(|basename| {
            basename == OsStr::new("flutter") || basename == OsStr::new("flutter.exe")
        })
}

/// The shim entry the CLI's argv0 dispatch calls: resolves the config
/// and the real flutter binary, runs the orchestrator, and returns the
/// process exit code — the child's whenever a child ran, 127 when no
/// flutter binary exists outside this shim (spawning bare `flutter`
/// would recurse into the shim itself).
#[must_use]
pub fn run_flutter_shim(argv: &[OsString]) -> i32 {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let config = match discover_shim_config(&cwd) {
        Ok(config) => config,
        Err(err) => {
            eprintln!("dartq-bcache: {err} (running flutter without the cache)");
            None
        }
    };
    let own_exe = std::env::current_exe().ok();
    let explicit = config.as_ref().and_then(|config| config.flutter_bin.as_deref());
    let Some(flutter) = discover_flutter(explicit, own_exe.as_deref()) else {
        eprintln!("dartq-bcache: no flutter executable found outside this shim");
        return 127;
    };
    let Some(mut config) = config else {
        return spawn_passthrough(&flutter, argv, &cwd);
    };
    config.flutter_bin = Some(flutter.clone());
    let mut runner = CommandRunner::new(flutter);
    run_shim(argv, &cwd, &config, &mut runner)
        .exit_code
        .unwrap_or(127)
}

/// The zero-config passthrough: flutter with the original argv, nothing
/// else — and no second process around it. `exec` replaces this shim
/// with flutter outright, so signals reach flutter directly and the
/// shim's memory goes away; the DARTQ_SHIM strip keeps a nested dartq
/// from mistaking the child for a shim. A runner that cannot replace
/// itself falls back to spawn-and-wait inside `exec`; a failed exec
/// reports and exits 127.
fn spawn_passthrough(flutter: &Path, argv: &[OsString], cwd: &Path) -> i32 {
    let mut runner = CommandRunner::new(flutter.to_path_buf());
    runner.exec(argv, cwd).unwrap_or_else(|err| {
        eprintln!("dartq-bcache: {err}");
        127
    })
}

/// What `dartq init` did.
#[derive(Debug, Clone)]
pub struct InitReport {
    /// The project's `dartq.yaml`.
    pub config_path: PathBuf,
    /// Whether the config was written (`false`: one already existed and
    /// was left untouched).
    pub config_written: bool,
    /// The installed (or blocked) shim path.
    pub shim_path: PathBuf,
    /// Whether the shim was (re)installed. `false` when a non-symlink
    /// occupies the path — a real file is never clobbered.
    pub shim_installed: bool,
    /// The exact `export PATH=...` line to print when the shim's bin
    /// directory is not on PATH.
    pub path_missing: Option<String>,
}

/// Why `dartq init` could not finish.
#[derive(Debug, thiserror::Error)]
pub enum InitError {
    #[error("io: {0}")]
    Io(#[from] io::Error),
    #[error("no home directory: the shim installs into ~/.dartq/bin")]
    NoHome,
}

/// `dartq init` for the current project and the invoking user's home.
///
/// # Errors
///
/// See [`init_in`].
pub fn init(project_dir: &Path) -> Result<InitReport, InitError> {
    let home = std::env::home_dir().ok_or(InitError::NoHome)?;
    let exe = std::env::current_exe()?;
    init_in(project_dir, &home, &exe)
}

/// The init core over injected home and executable (the testable seam):
/// writes the documented template when (and only when) no `dartq.yaml`
/// exists, then installs `~/.dartq/bin/flutter` as a symlink to `exe` —
/// replacing a stale symlink, never clobbering a real file. No shell rc
/// file is ever touched.
pub fn init_in(project_dir: &Path, home: &Path, exe: &Path) -> Result<InitReport, InitError> {
    let config_path = project_dir.join("dartq.yaml");
    let config_written = if config_path.is_file() {
        false
    } else {
        fs::write(&config_path, CONFIG_TEMPLATE)?;
        true
    };

    let bin_dir = home.join(".dartq").join("bin");
    fs::create_dir_all(&bin_dir)?;
    let shim = bin_dir.join("flutter");
    let existing = fs::symlink_metadata(&shim);
    let can_install = match &existing {
        Ok(meta) => meta.file_type().is_symlink(),
        Err(err) if err.kind() == io::ErrorKind::NotFound => true,
        Err(_) => false,
    };
    let mut shim_installed = false;
    if can_install {
        if existing.is_ok() {
            fs::remove_file(&shim)?;
        }
        install_shim(exe, &shim)?;
        shim_installed = true;
    }

    let path_missing = path_advice(&bin_dir, std::env::var_os("PATH"));
    Ok(InitReport {
        config_path,
        config_written,
        shim_path: shim,
        shim_installed,
        path_missing,
    })
}

/// Links `exe` at `target`: a symlink on unix; a file copy elsewhere
/// (symlink creation needs privileges on Windows).
fn install_shim(exe: &Path, target: &Path) -> Result<(), InitError> {
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(exe, target)?;
    }
    #[cfg(not(unix))]
    {
        fs::copy(exe, target)?;
    }
    Ok(())
}

/// The `export PATH=...` line to print when `bin_dir` is not on the
/// given PATH (exact directory match). `None` when it already is.
#[must_use]
fn path_advice(bin_dir: &Path, path_env: Option<OsString>) -> Option<String> {
    let on_path =
        path_env.is_some_and(|path| std::env::split_paths(&path).any(|dir| dir == bin_dir));
    (!on_path).then(|| format!("export PATH=\"{}:$PATH\"", bin_dir.display()))
}

/// `dartq bcache stats`: the store's size and age summary.
///
/// # Errors
///
/// [`BcacheError`] as the store reports it. Corrupt manifests are
/// counted in [`StoreStats::corrupt_manifests`], never fatal — one bad
/// file must not blind the budget; `gc` purges them.
pub fn bcache_stats(config: &ShimConfig) -> Result<StoreStats, BcacheError> {
    CasStore::open(&config.store_root)?.stats()
}

/// `dartq bcache gc`: the budget/LRU pass with the configured budget
/// and grace window.
///
/// # Errors
///
/// [`BcacheError`] as the store reports it.
pub fn bcache_gc(config: &ShimConfig) -> Result<GcReport, BcacheError> {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |since| since.as_secs());
    CasStore::open(&config.store_root)?.gc(config.budget_bytes, config.grace_secs, now)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let root = std::env::temp_dir().join(format!(
            "dq_cmd_bcache_{tag}_{}_{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("clock")
                .as_nanos()
        ));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).expect("scratch dir");
        root
    }

    fn write_config(dir: &Path, yaml: &str) {
        fs::write(dir.join("dartq.yaml"), yaml).expect("config");
    }

    /// A section maps to a full orchestrator config: the root gains the
    /// store's layout version, GiB → bytes, defaults apply.
    #[test]
    fn shim_config_maps_the_section_to_store_paths() {
        let section = BuildCacheConfig {
            root: Some(PathBuf::from("/store/cas")),
            budget_gb: Some(3),
            grace_secs: None,
            flutter: Some(PathBuf::from("/opt/flutter/bin/flutter")),
        };
        let config = shim_config(&section);
        assert_eq!(
            config.store_root,
            PathBuf::from("/store/cas").join(STORE_LAYOUT_VERSION)
        );
        assert_eq!(config.budget_bytes, 3 * 1024 * 1024 * 1024);
        assert_eq!(config.grace_secs, DEFAULT_GRACE_SECS);
        assert_eq!(config.flutter_bin, section.flutter);
        let defaults = default_shim_config();
        assert!(defaults.store_root.ends_with(STORE_LAYOUT_VERSION));
        assert_eq!(
            defaults.budget_bytes,
            DEFAULT_BUDGET_GB * 1024 * 1024 * 1024
        );
        assert_eq!(defaults.grace_secs, DEFAULT_GRACE_SECS);
    }

    /// The `flutter:` key expands `~` exactly like `root:` — the audit's
    /// 127 case was a literal `~/…` path handed to the spawn.
    #[test]
    fn flutter_bin_expands_tilde_like_the_root() {
        let home = std::env::home_dir().expect("home");
        let section = BuildCacheConfig {
            root: Some(PathBuf::from("~/cas")),
            budget_gb: None,
            grace_secs: None,
            flutter: Some(PathBuf::from("~/sdks/flutter")),
        };
        let config = shim_config(&section);
        assert_eq!(
            config.store_root,
            home.join("cas").join(STORE_LAYOUT_VERSION)
        );
        assert_eq!(config.flutter_bin, Some(home.join("sdks/flutter")));
    }

    #[test]
    fn expand_home_leaves_non_tilde_paths_literal() {
        assert_eq!(
            expand_home(Path::new("/abs/root")),
            PathBuf::from("/abs/root")
        );
        assert_eq!(expand_home(Path::new("relative")), PathBuf::from("relative"));
    }

    /// The default store root resolves like the session registry's
    /// cache root: `$XDG_CACHE_HOME` wins, else the home's `.cache`.
    #[test]
    fn default_cache_root_honors_xdg_then_home() {
        let root = scratch("xdg");
        let xdg = root.join("xdg-cache");
        fs::create_dir_all(&xdg).expect("mkdir xdg");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("mkdir home");

        assert_eq!(
            cache_root_from(Some(xdg.clone().into_os_string()), Some(home.clone())),
            xdg.join("dartq").join("cas")
        );
        assert_eq!(
            cache_root_from(None, Some(home.clone())),
            home.join(".cache").join("dartq").join("cas")
        );
        assert_eq!(
            cache_root_from(None, None),
            PathBuf::from("dartq").join("cas")
        );
        assert!(default_cache_root().ends_with("cas"));
    }

    #[test]
    fn discovery_walks_up_and_maps_the_section() {
        let root = scratch("discover");
        let project = root.join("deep").join("project");
        fs::create_dir_all(&project).expect("mkdir");
        write_config(&root, "build_cache:\n  budget_gb: 3\n  root: /store/cas\n");
        let config = discover_shim_config(&project)
            .expect("discover")
            .expect("some");
        assert_eq!(
            config.store_root,
            PathBuf::from("/store/cas").join(STORE_LAYOUT_VERSION)
        );
        assert_eq!(config.budget_bytes, 3 * 1024 * 1024 * 1024);

        // No section anywhere: None, with no side effects.
        let bare = scratch("bare");
        assert!(discover_shim_config(&bare).expect("discover").is_none());
        write_config(&bare, "cache:\n  size_limit_gib: 1\n");
        assert!(discover_shim_config(&bare).expect("discover").is_none());
        fs::remove_dir_all(&root).ok();
        fs::remove_dir_all(&bare).ok();
    }

    #[test]
    fn argv0_dispatch_decision() {
        assert!(is_shim_invocation(Some(OsStr::new("flutter"))));
        assert!(is_shim_invocation(Some(
            OsStr::new("/opt/dartq-shims/flutter")
        )));
        // The Windows spelling of the shim name, as a pure name check.
        assert!(is_shim_invocation(Some(OsStr::new("flutter.exe"))));
        assert!(is_shim_invocation(Some(
            OsStr::new("/opt/dartq-shims/flutter.exe")
        )));
        assert!(!is_shim_invocation(Some(OsStr::new("dartq"))));
        assert!(!is_shim_invocation(Some(OsStr::new("/usr/local/bin/dart"))));
        assert!(!is_shim_invocation(Some(OsStr::new("flutter.exe.bak"))));
        assert!(!is_shim_invocation(None));
    }

    #[test]
    fn init_writes_config_installs_shim_and_never_clobbers() {
        let root = scratch("init");
        let home = root.join("home");
        let project = root.join("project");
        fs::create_dir_all(&home).expect("mkdir home");
        fs::create_dir_all(&project).expect("mkdir project");
        let exe = root.join("bin").join("dartq");
        fs::create_dir_all(exe.parent().expect("parent")).expect("mkdir");
        fs::write(&exe, b"dartq binary bytes").expect("exe");

        let report = init_in(&project, &home, &exe).expect("init");
        assert!(report.config_written);
        let config = fs::read_to_string(&report.config_path).expect("config");
        assert!(config.contains("build_cache:"));
        assert!(config.contains("# budget_gb: 40"));
        assert!(report.shim_installed);
        assert_eq!(
            fs::read_link(&report.shim_path).expect("symlink"),
            exe,
            "the symlink stores the executable path as given"
        );
        let expected = format!(
            "export PATH=\"{}:$PATH\"",
            home.join(".dartq").join("bin").display()
        );
        assert_eq!(
            report.path_missing.as_deref(),
            Some(expected.as_str()),
            "the temp home bin dir is not on a test PATH"
        );

        // A second init never rewrites the config and refreshes the
        // symlink; a pre-existing real file at the shim path is left
        // alone.
        fs::write(&report.config_path, "version: 1\n").expect("user config");
        let again = init_in(&project, &home, &exe).expect("init again");
        assert!(!again.config_written);
        assert_eq!(
            fs::read_to_string(&report.config_path).expect("config"),
            "version: 1\n"
        );
        assert!(again.shim_installed);

        fs::remove_file(&report.shim_path).expect("remove symlink");
        fs::write(&report.shim_path, b"a real flutter").expect("real file");
        let blocked = init_in(&project, &home, &exe).expect("init blocked");
        assert!(!blocked.shim_installed);
        assert_eq!(
            fs::read(&report.shim_path).expect("untouched"),
            b"a real flutter".to_vec()
        );
        fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn stats_and_gc_faces_drive_the_store() {
        let root = scratch("stats");
        let config = ShimConfig {
            store_root: root.join("cas").join(STORE_LAYOUT_VERSION),
            budget_bytes: 0,
            grace_secs: 0,
            flutter_bin: None,
        };
        let stats = bcache_stats(&config).expect("empty stats");
        assert_eq!(stats, StoreStats::default());
        let report = bcache_gc(&config).expect("gc");
        assert_eq!(report, GcReport::default());
        fs::remove_dir_all(&root).ok();
    }
}
