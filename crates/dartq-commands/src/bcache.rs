    /// The note's version source is the SDK's `flutter.version.json` —
    /// the manifest the toolchain fingerprint reads — resolved from the
    /// binary through the same root derivation.
    #[test]
    fn framework_version_of_reads_the_sdk_manifest() {
        let root = scratch("version");
        let sdk = root.join("flutter-sdk");
        let bin = sdk.join("bin");
        fs::create_dir_all(bin.join("cache")).expect("mkdir sdk");
        fs::write(bin.join("flutter"), b"#!/bin/sh\n").expect("flutter binary");
        fs::write(
            bin.join("cache").join("flutter.version.json"),
            br#"{"frameworkVersion": "3.30.2", "channel": "stable"}"#,
        )
        .expect("manifest");
        assert_eq!(
            framework_version_of(&bin.join("flutter")).as_deref(),
            Some("3.30.2")
        );
        // An unrooted or manifest-less binary stays silent.
        assert_eq!(framework_version_of(&root.join("nowhere")), None);
        fs::remove_dir_all(&root).ok();
    }

