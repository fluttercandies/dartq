    /// The shim install lifecycle: fresh → Installed; the same
    /// executable again → AlreadyPresent; a stale link is refreshed; a
    /// real file is never clobbered; remove takes down the link only.
    #[test]
    fn shim_install_and_remove_never_touch_a_real_file() {
        let root = scratch("shim");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("mkdir home");
        let exe = root.join("bin").join("dartq");
        fs::create_dir_all(exe.parent().expect("parent")).expect("mkdir");
        fs::write(&exe, b"dartq binary bytes").expect("exe");
        let shim = home.join(".dartq").join("bin").join("flutter");

        let (outcome, path) = shim_install_in(&home, &exe).expect("install");
        assert_eq!(outcome, ShimOutcome::Installed);
        assert_eq!(path, shim);
        assert_eq!(
            fs::read_link(&shim).expect("symlink"),
            exe,
            "the symlink stores the executable path as given"
        );

        // Idempotent: a second install of the same executable leaves the
        // link untouched.
        let (outcome, _) = shim_install_in(&home, &exe).expect("install again");
        assert_eq!(outcome, ShimOutcome::AlreadyPresent);
        assert_eq!(fs::read_link(&shim).expect("symlink"), exe);

        // A stale link (a moved dartq) is refreshed to the new
        // executable.
        let moved = root.join("bin").join("dartq-moved");
        fs::rename(&exe, &moved).expect("move");
        let (outcome, _) = shim_install_in(&home, &moved).expect("refresh");
        assert_eq!(outcome, ShimOutcome::Installed);
        assert_eq!(fs::read_link(&shim).expect("symlink"), moved);

        // Remove takes the link down and reports nothing-installed after.
        let (outcome, _) = shim_remove_at(&home).expect("remove");
        assert_eq!(outcome, ShimOutcome::Removed);
        assert!(!shim.exists());
        let (outcome, _) = shim_remove_at(&home).expect("remove again");
        assert_eq!(outcome, ShimOutcome::NotInstalled);

        // A real file at the path is refused by both faces and left
        // byte-identical.
        fs::create_dir_all(shim.parent().expect("bin")).expect("bin");
        fs::write(&shim, b"a real flutter").expect("real file");
        let (outcome, _) = shim_install_in(&home, &moved).expect("install blocked");
        assert_eq!(outcome, ShimOutcome::Blocked);
        let (outcome, _) = shim_remove_at(&home).expect("remove blocked");
        assert_eq!(outcome, ShimOutcome::Blocked);
        assert_eq!(
            fs::read(&shim).expect("untouched"),
            b"a real flutter".to_vec()
        );

        // The PATH advice names the bin dir exactly when it is absent
        // from the PATH it is checked against.
        let bin_dir = home.join(".dartq").join("bin");
        assert_eq!(
            path_advice(&bin_dir, None).as_deref(),
            Some(format!("export PATH=\"{}:$PATH\"", bin_dir.display()).as_str()),
            "no PATH means the advice prints"
        );
        assert_eq!(
            path_advice(&bin_dir, Some(bin_dir.clone().into_os_string())),
            None,
            "a bin dir already on PATH needs no advice"
        );
        fs::remove_dir_all(&root).ok();
    }

