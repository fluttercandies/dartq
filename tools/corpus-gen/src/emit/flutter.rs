/// Widget host file of one host/part pair (#2063 shape): a
/// `StatefulWidget` whose private `State` builds a nested tree of stub
/// widgets. Content derives from `(package, index)` only — no RNG draws, so
/// the bytes are scale-invariant and pinnable.
pub(super) fn widget_host(w: &mut String, package: u32, index: usize) {
    let rows = index % 5 + 1;
    dw!(
        w,
        "// Generated by corpus-gen. Deterministic corpus; do not edit.\n\n"
    );
    dw!(
        w,
        "/// Widget host file: a StatefulWidget whose State builds a nested\n/// stub-widget tree; the part file contributes a private leaf widget.\n"
    );
    dw!(w, "import 'package:flutter/widgets.dart';\n\n");
    dw!(w, "part 'widget_{index:05}_part.dart';\n\n");
    dw!(w, "/// Stateful host widget of this file pair.\n");
    dw!(
        w,
        "class HostWidget{package}_{index} extends StatefulWidget {{\n  const HostWidget{package}_{index}({{super.key, this.rows = {rows}}});\n\n  final int rows;\n\n  @override\n  State<HostWidget{package}_{index}> createState() =>\n      _HostWidget{package}_{index}State();\n}}\n\n"
    );
    dw!(
        w,
        "/// Private state: a tap counter and the nested build tree.\n"
    );
    dw!(
        w,
        "class _HostWidget{package}_{index}State extends State<HostWidget{package}_{index}> {{\n  int _taps = 0;\n\n  void _bump() {{\n    setState(() {{\n      _taps += 1;\n    }});\n  }}\n\n  @override\n  Widget build(BuildContext context) {{\n    return Scaffold(\n      appBar: AppBar(title: Text('host-{package:04}-{index:05}')),\n      body: Center(\n        child: Column(\n          children: <Widget>[\n            Text('taps: $_taps'),\n            for (var i = 0; i < widget.rows; i++)\n              Padding(\n                padding: const EdgeInsets.all(2),\n                child: _TileWidget{package}_{index}('row $i'),\n              ),\n            TextButton(onPressed: _bump, child: const Text('bump')),\n            Container(\n              key: ValueKey<int>(_taps),\n              child: Text('total ${{_taps * widget.rows}}'),\n            ),\n          ],\n        ),\n      ),\n    );\n  }}\n}}\n"
    );
}

