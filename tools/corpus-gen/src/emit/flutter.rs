/// Widget rotation scene (#2063): every 4th rotation file under the
/// flutter-app face becomes one of these instead of the plain scene cells.
/// Two deterministic variants rotate on the file ordinal: a nested
/// stateless tree and an app shell. `ordinal` is the rotation file's global
/// ordinal, which keeps class names corpus-unique.
pub(super) fn rotation_scene(w: &mut String, ordinal: usize) {
    dw!(
        w,
        "// Generated by corpus-gen. Deterministic corpus; do not edit.\n"
    );
    dw!(w, "import 'package:flutter/widgets.dart';\n\n");
    if ordinal % 2 == 0 {
        dw!(
            w,
            "/// Widget rotation scene: a StatelessWidget building a nested tree.\n"
        );
        dw!(
            w,
            "class CardScene{ordinal} extends StatelessWidget {{\n  const CardScene{ordinal}({{super.key}});\n\n  @override\n  Widget build(BuildContext context) {{\n    return Container(\n      child: Row(\n        children: <Widget>[\n          const Text('card-{ordinal}'),\n          for (var i = 0; i < 3; i++)\n            Padding(\n              padding: const EdgeInsets.all(1),\n              child: Text('item $i'),\n            ),\n        ],\n      ),\n    );\n  }}\n}}\n"
        );
    } else {
        dw!(
            w,
            "/// Widget rotation scene: an app shell over the stub surface.\n"
        );
        dw!(
            w,
            "class ShellScene{ordinal} extends StatelessWidget {{\n  const ShellScene{ordinal}({{super.key}});\n\n  @override\n  Widget build(BuildContext context) {{\n    return MaterialApp(\n      title: 'scene-{ordinal}',\n      child: Scaffold(\n        appBar: AppBar(title: const Text('shell-{ordinal}')),\n        body: Center(\n          child: Column(\n            children: <Widget>[\n              for (var i = 0; i < 2; i++) Text('row $i'),\n              const TextButton(onPressed: null, child: Text('idle')),\n            ],\n          ),\n        ),\n      ),\n    );\n  }}\n}}\n"
        );
    }
}
