//! The `--flutter-app` face (#2063): the in-corpus `packages/flutter` stub
//! package and the real widget-shape emitters.
//!
//! The stub is a hand-shaped subset of the real Flutter widget surface
//! (upstream Flutter SDK source, `packages/flutter/lib/src/widgets/framework.dart`,
//! surface signatures only — no elements, no rendering): just enough typed
//! API that generated app code — `StatefulWidget`/`State` pairs with nested
//! `build` trees — analyzes cleanly under dart 3.13 on both sides of the
//! differential. Oracle and dartq analyze identical sources, so parity stays
//! `dart analyze`-over-identical-sources with no Flutter SDK or network.
//!
//! Determinism contract: every emitter here derives its content from
//! `(package, index)` / `ordinal` arithmetic and never draws from the shared
//! RNG stream, so the stub bytes and each widget-file's bytes are
//! scale-invariant — the app-x golden check can pin them.

