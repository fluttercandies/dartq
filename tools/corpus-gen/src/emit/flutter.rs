/// One `part` file of the stub library; `index` addresses
/// [`crate::plan::FLUTTER_PARTS`].
pub(super) fn stub_part(w: &mut String, index: usize) {
    match crate::plan::FLUTTER_PARTS[index] {
        "basic" => basic_part(w),
        "foundation" => foundation_part(w),
        "material" => material_part(w),
        other => unreachable!("unknown flutter stub part {other}"),
    }
}

