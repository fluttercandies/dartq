//! Adversarial overlay renderers (#1810): pathological singles, the unicode
//! edge family, and recovery-storm files under `zadv/`.
//!
//! These renderers run strictly after every base-corpus file, so the shared
//! RNG draws here can never perturb the bytes of any pre-overlay file.

use super::RenderCtx;
use crate::coverage::Cell;
use std::fmt::Write as _;

// --- 1a: pathological singles ------------------------------------------------

/// Depth/size budgets per shape. The parser's per-file diagnostic fuse is
/// 10k, so the stress axis is size and nesting depth, not error count: every
/// budget below renders syntactically VALID Dart.
const PATHO_NEST_DEPTH: usize = 1_000; // nested list literal depth
// Oracle crash bracket (2026-10-18, #2148): dart analyze 3.13.1 dies rc=255
// "Internal error: Stack Overflow" on a left-nested `+` chain of 4,000
// terms — unguarded recursive AST walks in the analyzer (repro trace tops at
// NullSafetyDeadCodeVerifier.visitNode; at 20k terms the overflow instead
// surfaces in summary2/informative_data.dart); 2,000 terms analyze clean.
// 2,000 keeps the giant-expression stress inside the verified-clean regime —
// do not raise without re-running that bracket.
const PATHO_EXPR_TOKENS: usize = 2_000; // terms in one giant expression
const PATHO_SWITCH_ARMS: usize = 600; // switch-expression arms
const PATHO_CASCADE_LEN: usize = 800; // `..add(k)` chain length
const PATHO_INTERP_CHAIN: usize = 400; // adjacent interpolated segments
const PATHO_CLOSURE_NEST: usize = 300; // nested closure invocations

/// Renders one `zadv/patho/patho_NNNNN.dart`. Six shapes rotate on `index`;
/// the same index always yields the same shape and budget.
pub(super) fn patho(w: &mut String, ctx: &mut RenderCtx<'_>, index: usize) {
    dw!(
        w,
        "// Generated by corpus-gen. Deterministic corpus; do not edit.\n"
    );
    dw!(
        w,
        "// Pathological single file (axis 1a), shape {}.\n",
        index % 6
    );
    match index % 6 {
        0 => patho_nested_collection(w),
        1 => patho_mega_expression(w),
        2 => patho_giant_switch(w),
        3 => patho_cascade(w),
        4 => patho_interpolation_chain(w),
        _ => patho_closure_nest(w),
    }
    ctx.coverage.hit(Cell::PathoSingle);
}

/// Nested list literal, [`PATHO_NEST_DEPTH`] levels deep: `[ [ [ ... 0 ... ] ] ]`.
fn patho_nested_collection(w: &mut String) {
    w.push_str("\nfinal deepNested = ");
    for _ in 0..PATHO_NEST_DEPTH {
        w.push('[');
    }
    w.push('0');
    for _ in 0..PATHO_NEST_DEPTH {
        w.push(']');
    }
    w.push_str(";\n");
}

/// One giant expression: `0+1+2+...` — ~[`PATHO_EXPR_TOKENS`] tokens in a
/// single expression statement.
fn patho_mega_expression(w: &mut String) {
    w.push_str("\nfinal megaSum = ");
    for k in 0..PATHO_EXPR_TOKENS {
        if k > 0 {
            w.push('+');
        }
        write!(w, "{}", k % 10).expect("string write");
    }
    w.push_str(";\n");
}

/// Giant switch expression with [`PATHO_SWITCH_ARMS`] constant arms.
fn patho_giant_switch(w: &mut String) {
    w.push_str("\nString giantSwitch(int v) => switch (v) {\n");
    for arm in 0..PATHO_SWITCH_ARMS {
        writeln!(w, "      {arm} => 'a{arm}',").expect("string write");
    }
    w.push_str("      _ => 'z',\n    };\n");
}

/// Mega cascade chain on a `StringBuffer`: [`PATHO_CASCADE_LEN`] `..write()`
/// segments.
fn patho_cascade(w: &mut String) {
    w.push_str("\nString megaCascade() {\n  final b = StringBuffer()\n");
    for k in 0..PATHO_CASCADE_LEN {
        writeln!(w, "    ..write('s{k}')").expect("string write");
    }
    w.push_str("  ;\n  return b.toString();\n}\n");
}

/// One string built from [`PATHO_INTERP_CHAIN`] adjacent interpolated
/// segments: 'a${x}b${x}c...'.
fn patho_interpolation_chain(w: &mut String) {
    w.push_str("\nString interpChain(int x) =>\n    '");
    for k in 0..PATHO_INTERP_CHAIN {
        write!(w, "s{k}=${{x + {k}}}|").expect("string write");
    }
    w.push_str("';\n");
}

/// Nested immediately-invoked closures, [`PATHO_CLOSURE_NEST`] deep.
fn patho_closure_nest(w: &mut String) {
    w.push_str("\nfinal closureNest = ");
    for k in 0..PATHO_CLOSURE_NEST {
        write!(w, "() => (k{k} => ").expect("string write");
    }
    w.push('0');
    for _ in 0..PATHO_CLOSURE_NEST {
        w.push_str(")(0)");
    }
    w.push_str(";\n");
}

// --- 1b: unicode edge family -------------------------------------------------

/// Renders one `zadv/unicode/uni_NNNNN.dart`. Identifiers stay ASCII (Dart
/// scanner law); all unicode lives in string literals, doc/line comments and
/// one URI literal. `index % 8` selects the shape mix; every file hits the
/// `unicode_content` cell once.
pub(super) fn unicode_scene(w: &mut String, ctx: &mut RenderCtx<'_>, index: usize) {
    let rng = &mut *ctx.rng;
    // A deterministic subset of files carries a leading BOM: the decode
    // faces strip a file-origin U+FEFF, so this is a valid edge shape.
    if index % 8 == 3 {
        w.push('\u{FEFF}');
    }
    dw!(
        w,
        "// Generated by corpus-gen. Deterministic corpus; do not edit.\n"
    );
    let k = rng.below(1_000);
    match index % 8 {
        0 => unicode_rtl(w, k),
        1 => unicode_combining(w, k),
        2 => unicode_astral(w, k),
        3 => unicode_emoji_zwj(w, k),
        4 => unicode_zero_width(w, k),
        5 => unicode_doc_comments(w, k),
        6 => unicode_uri(w, k),
        _ => unicode_ident_edge(w, k),
    }
    ctx.coverage.hit(Cell::UnicodeContent);
}

/// RTL script string content (Arabic + Hebrew) — content only, never an
/// identifier.
fn unicode_rtl(w: &mut String, k: u64) {
    w.push_str("\n/// RTL script literals.\n");
    write!(
        w,
        "const rtlGreeting{k} = 'مرحبا بالعالم';\nconst rtlHebrew{k} = 'שלום עולם';\nconst rtlMixed{k} = 'a مرحبا b שלום c {k}';\n"
    )
    .expect("string write");
}

/// Combining-mark sequences inside a string literal (base char + U+0301
/// combining acute + U+0308 combining diaeresis).
fn unicode_combining(w: &mut String, k: u64) {
    w.push_str("\n/// Combining-mark sequences.\n");
    writeln!(
        w,
        "const combining{k} = 'e\u{0301}a\u{0308}o\u{0308}n\u{0303} {k}';"
    )
    .expect("string write");
}

/// Astral-plane content both as `\u{...}` escapes and as raw astral
/// characters (deseret capital, CJK extension B).
fn unicode_astral(w: &mut String, k: u64) {
    w.push_str("\n/// Astral escapes and raw astral characters.\n");
    writeln!(
        w,
        "const astralEsc{k} = '\\u{{1F600}}\\u{{10FFFF}}\\u{{20000}}';\nconst astralRaw{k} = '\u{1F600}\u{10400}\u{20000} tail {k}';"
    )
    .expect("string write");
}

/// Emoji and zero-width-joiner sequences inside a string literal.
fn unicode_emoji_zwj(w: &mut String, k: u64) {
    w.push_str("\n/// Emoji and ZWJ sequences.\n");
    writeln!(
        w,
        "const emojiZwj{k} = '\u{1F468}\u{200D}\u{1F469}\u{200D}\u{1F467} \u{1F600}\u{1F44D} {k}';"
    )
    .expect("string write");
}

/// Zero-width characters (U+200B space, U+200C non-joiner, U+FEFF mark)
/// inside a string literal — legal string content, invisible bytes.
fn unicode_zero_width(w: &mut String, k: u64) {
    w.push_str("\n/// Zero-width characters in string content.\n");
    writeln!(
        w,
        "const zeroWidth{k} = 'a\u{200B}b\u{200C}c\u{FEFF}d {k}';"
    )
    .expect("string write");
}

/// Doc comments carrying unicode prose plus a mixed-direction line comment.
fn unicode_doc_comments(w: &mut String, k: u64) {
    w.push_str("\n/// Unicode doc-comment content: 汉字 日本語 한국어.\n");
    writeln!(
        w,
        "/// \u{00C9}tude {k} — \u{202E}reversed-marker\u{202C} reset."
    )
    .expect("string write");
    writeln!(
        w,
        "const docHolder{k} = 0;\n// trailing 注释 comment \u{1F4DD}"
    )
    .expect("string write");
}

/// Percent-encoded + literal unicode inside an import-URI string literal.
/// The URI is still a plain string to the scanner; whether it resolves is a
/// later layer's concern.
fn unicode_uri(w: &mut String, k: u64) {
    w.push_str("\n/// Unicode in URI literals (percent-encoded and raw).\n");
    writeln!(
        w,
        "import 'package:nonexistent/caf%C3%A9_{k}.dart';\nimport 'dart:core' as core{k};\nconst uriNote{k} = 'import of caf\u{00E9}';"
    )
    .expect("string write");
}

/// Non-ASCII identifier adjacency: `var fooé` — the scanner merges the
/// illegal char into the adjacent Identifier token (`NonAsciiIdentifierToken`
/// recovery) and reports `illegal_character`. Deliberately diagnostic-bearing.
fn unicode_ident_edge(w: &mut String, k: u64) {
    w.push_str("\n/// Non-ASCII identifier edge (recovery-merge shape).\n");
    write!(
        w,
        "final identEdge{k} = 'value';\nfinal caf\u{00E9}tail{k} = 0;\n"
    )
    .expect("string write");
}

// --- 1c: recovery storms -----------------------------------------------------

/// One stacked-damage construct: a small, self-contained malformed Dart
/// fragment drawn from the `tests/corpus/recovery` taxonomy. Every recipe is
/// 5-10 lines and reports at least one parse-level diagnostic.
const DAMAGE_RECIPES: &[&str] = &[
    // paired_tokens/braces — unclosed `{` in a function body.
    "f{u}(x) {\n  if (x != null) {\n",
    // paired_tokens/parentheses — missing `)` after the condition.
    "g{u}(x) {\n  if (x\n  while (x != null) {}\n}\n",
    // missing_code — missing comma in a list literal.
    "h{u}() => [a{u}, b{u} c{u}];\n",
    // missing_code — conditional expression missing the `then` branch.
    "k{u}() => x{u} ? : z{u};\n",
    // code_order/class_declaration — `implements` before `extends`.
    "class StormA{u} implements StormB{u} extends StormC{u} {}\n",
    // code_order/try_statement — `finally` before `catch`.
    "t{u}() {\n  try {\n  } finally {\n  } catch (e) {\n  }\n}\n",
    // code_order/mixin_declaration — doubled `on` clause.
    "mixin StormM{u} on StormB{u} on StormC{u} {}\n",
    // extra_code/modifiers — `static` on a top-level class.
    "static class StormExtra{u} {}\n",
    // paired_tokens/brackets — unclosed `[` in an expression.
    "v{u}() => [1, 2, 3;\n",
    // paired_tokens/angle_brackets — unclosed `<` in a type argument list.
    "Map<String, int m{u}() => {};\n",
];

/// Declarations the recipes reference: enough symbols for the damage to read
/// as stacked real-code breakage rather than free-floating fragments.
fn storm_prelude(w: &mut String, package: u32, file: usize) {
    write!(
        w,
        "// Generated by corpus-gen. Deterministic corpus; do not edit.\n// Recovery storm (axis 1c) — >=5 stacked malformed constructs.\n\nclass StormB{package}_{file} {{}}\nclass StormC{package}_{file} {{}}\n"
    )
    .expect("string write");
    write!(
        w,
        "final a{package}_{file} = 0;\nfinal b{package}_{file} = 0;\nfinal c{package}_{file} = 0;\nfinal x{package}_{file} = 0;\nfinal z{package}_{file} = 0;\n\n"
    )
    .expect("string write");
}

/// Renders one `zadv/errstorm_NNNN/lib/storm_MMMMM.dart`: a prelude of valid
/// declarations plus >=5 damage recipes selected deterministically from the
/// seed stream.
pub(super) fn errstorm(w: &mut String, ctx: &mut RenderCtx<'_>, package: u32, file: usize) {
    storm_prelude(w, package, file);
    let rng = &mut *ctx.rng;
    // 5-8 stacked recipes per file; `u` uniquifies colliding declaration
    // names inside one file.
    let recipe_count = 5 + usize::try_from(rng.below(4)).expect("count fits usize");
    for u in 0..recipe_count {
        let recipe =
            usize::try_from(rng.below(DAMAGE_RECIPES.len() as u64)).expect("recipe index fits");
        let body = DAMAGE_RECIPES[recipe].replace("{u}", &format!("{package}_{file}_{u}"));
        w.push_str(&body);
        w.push('\n');
    }
    ctx.coverage.hit(Cell::RecoveryStorm);
}

/// `zadv/errstorm_NNNN/pubspec.yaml` — standalone package, no dependencies.
pub(super) fn errstorm_pubspec(w: &mut String, package: u32) {
    dw!(
        w,
        "# Generated by corpus-gen. Deterministic corpus; do not edit.\n"
    );
    dw!(w, "name: errstorm_{package:04}\n");
    dw!(
        w,
        "description: Recovery-storm package {package:04} of the generated dartq stress corpus.\n"
    );
    dw!(w, "version: 1.0.0\n");
    dw!(w, "publish_to: none\n\n");
    dw!(w, "environment:\n  sdk: ^3.13.0\n");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::coverage::Coverage;
    use crate::plan::{Plan, Scale};

    fn ctx<'a>(
        plan: &'a Plan,
        rng: &'a mut crate::rng::SplitMix64,
        coverage: &'a mut Coverage,
    ) -> RenderCtx<'a> {
        RenderCtx {
            plan,
            rng,
            coverage,
            rotation_ordinal: 0,
        }
    }

    /// Every patho shape renders and stays inside its structural budget: the
    /// parser fuse is 10k diagnostics, so the stress axis is depth/size on
    /// VALID syntax — nothing here may produce a malformed file.
    #[test]
    fn all_patho_shapes_render_within_budgets() {
        let plan = Plan::build(Scale::K1);
        for shape in 0..6usize {
            let mut rng = crate::rng::SplitMix64::new(42);
            let mut coverage = Coverage::new();
            let mut ctx = ctx(&plan, &mut rng, &mut coverage);
            let mut w = String::new();
            patho(&mut w, &mut ctx, shape);
            let opens = w.matches('[').count();
            let closes = w.matches(']').count();
            assert_eq!(opens, closes, "unbalanced brackets in shape {shape}");
            // Depth caps: nested collection reaches 1000, others stay under.
            match shape {
                0 => assert!(opens == PATHO_NEST_DEPTH),
                1 => assert!(w.matches('+').count() >= PATHO_EXPR_TOKENS - 1),
                2 => assert!(w.matches("=>").count() >= PATHO_SWITCH_ARMS),
                3 => assert!(w.matches("..write").count() == PATHO_CASCADE_LEN),
                4 => assert!(w.matches("${").count() == PATHO_INTERP_CHAIN),
                _ => assert!(w.matches(") => (").count() == PATHO_CLOSURE_NEST),
            }
            assert_eq!(ctx.coverage.count(Cell::PathoSingle), 1);
        }
    }

    /// Every unicode family variant emits and hits the coverage cell once.
    #[test]
    fn all_unicode_variants_emit() {
        let plan = Plan::build(Scale::K1);
        for variant in 0..8usize {
            let mut rng = crate::rng::SplitMix64::new(1);
            let mut coverage = Coverage::new();
            let mut ctx = ctx(&plan, &mut rng, &mut coverage);
            let mut w = String::new();
            unicode_scene(&mut w, &mut ctx, variant);
            assert!(!w.is_empty(), "empty unicode variant {variant}");
            assert_eq!(ctx.coverage.count(Cell::UnicodeContent), 1);
        }
    }

    /// The storm recipe table must cover the recovery taxonomy's categories
    /// and every recipe must carry the `{u}` uniquifier placeholder.
    #[test]
    fn storm_recipes_are_uniquified_and_taxonomy_covering() {
        assert_eq!(DAMAGE_RECIPES.len(), 10);
        for recipe in DAMAGE_RECIPES {
            assert!(recipe.contains("{u}"), "recipe lacks uniquifier: {recipe}");
        }
        // One storm file renders 5-8 recipe bodies.
        let plan = Plan::build(Scale::K1);
        let mut rng = crate::rng::SplitMix64::new(7);
        let mut coverage = Coverage::new();
        let mut ctx = ctx(&plan, &mut rng, &mut coverage);
        let mut w = String::new();
        errstorm(&mut w, &mut ctx, 0, 0);
        let instances = (0..8).filter(|u| w.contains(&format!("0_0_{u}"))).count();
        assert!(instances >= 5, "fewer than 5 damage instances: {instances}");
        assert_eq!(ctx.coverage.count(Cell::RecoveryStorm), 1);
    }
}
