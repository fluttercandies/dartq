"""Shared helpers for the torture corpus generator.

Everything here is a pure function of its arguments: no RNG, no clock, no
environment lookups. Regenerating the corpus with the same seed is
byte-identical by construction.
"""

from __future__ import annotations

import json
import os

GENERATOR_REL = "tests/corpus/torture/tools/gen_torture.py"
LANGUAGE_VERSION = "3.13"
SDK_CONSTRAINT = "^3.13.0"

# Every package name emitted by the generator (root app package excluded).
PKG_CORE = "core_types"
PKG_MOD_PROVIDER = "mod_provider"
CHAIN_PKGS = [f"chain_{i:02d}" for i in range(8)]
MIX_PKGS = [f"mix_{i:02d}" for i in range(4)]
MODC_PKGS = [f"modc_{i:02d}" for i in range(2)]
EXTT_PKGS = [f"extt_{i:02d}" for i in range(2)]
PAT_PKGS = [f"pat_{i:02d}" for i in range(3)]
GEN_PKGS = [f"gen_{i:02d}" for i in range(4)]
ASYNC_PKGS = [f"asyncx_{i:02d}" for i in range(3)]
MISC_PKGS = [f"misc_{i:02d}" for i in range(3)]
PKG_ERRPROBE = "errprobe"
PKG_APP = "torture"

ALL_PACKAGES = (
    [PKG_CORE, PKG_MOD_PROVIDER]
    + CHAIN_PKGS
    + MIX_PKGS
    + MODC_PKGS
    + EXTT_PKGS
    + PAT_PKGS
    + GEN_PKGS
    + ASYNC_PKGS
    + MISC_PKGS
    + [PKG_ERRPROBE]
)


def header(seed: int) -> str:
    """Standard first-line comment for every generated Dart file."""
    return (
        f"// Generated by {GENERATOR_REL} (seed {seed}). "
        "Deterministic corpus; do not edit by hand."
    )


def dart_file(seed: int, body: str) -> str:
    """Assemble a Dart file: header comment, blank line, body."""
    text = header(seed) + "\n\n" + body.strip("\n") + "\n"
    return text


def pubspec_text(name: str, description: str, deps: list[str]) -> str:
    """pubspec.yaml for a generated package (path dependencies only)."""
    lines = [
        f"# Generated by {GENERATOR_REL}. Deterministic corpus; do not edit by hand.",
        f"name: {name}",
        f"description: {description}",
        "version: 1.0.0",
        "publish_to: none",
        "",
        "environment:",
        f"  sdk: {SDK_CONSTRAINT}",
    ]
    if deps:
        lines.append("")
        lines.append("dependencies:")
        for dep in sorted(deps):
            lines.append(f"  {dep}:")
            lines.append(f"    path: packages/{dep}")
    return "\n".join(lines) + "\n"


def package_config_text() -> str:
    """Materialized .dart_tool/package_config.json for the corpus root.

    Mirrors the conventions of the other analyzer-facing corpora: relative
    rootUris, one entry per packages/* dependency plus the self entry
    (rootUri "../") last, languageVersion 3.13 everywhere. No absolute
    paths: this file is regenerable and safe to diff.
    """
    entries = []
    for pkg in ALL_PACKAGES:
        entries.append(
            {
                "name": pkg,
                "rootUri": f"../packages/{pkg}",
                "packageUri": "lib/",
                "languageVersion": LANGUAGE_VERSION,
            }
        )
    entries.append(
        {
            "name": PKG_APP,
            "rootUri": "../",
            "packageUri": "lib/",
            "languageVersion": LANGUAGE_VERSION,
        }
    )
    doc = {
        "configVersion": 2,
        "packages": entries,
        "generator": "pub",
        "generatorVersion": "3.13.1",
    }
    return json.dumps(doc, indent=2) + "\n"


def write_corpus(out_dir: str, files: dict[str, str]) -> None:
    """Write every file (relpath -> text) under out_dir, creating dirs."""
    for rel in sorted(files):
        path = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(files[rel])


def pkg_dep(pkg: str) -> str:
    """The package: import prefix for a generated dependency package."""
    return f"package:{pkg}/"


def counts_by_prefix(files: dict[str, str]) -> dict[str, int]:
    """File count per top-level package dir (packages/<name> or root)."""
    out: dict[str, int] = {}
    for rel in files:
        parts = rel.split(os.sep)
        if parts[0] == "packages" and len(parts) > 1:
            key = parts[1]
        else:
            key = PKG_APP
        out[key] = out.get(key, 0) + 1
    return out
